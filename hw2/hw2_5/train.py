import torch
from torch.utils.data import DataLoader
from torchvision import datasets,transforms,ops
from torchvision.transforms import ToTensor, Resize
from torchvision.models import resnet50
import torch.nn as nn
from tqdm import tqdm,trange
from PIL import ImageFile
ImageFile.LOAD_TRUNCATED_IMAGES = True
import warnings # 忽略警告訊息 
warnings.filterwarnings("ignore")

device = "cuda" if torch.cuda.is_available() else "cpu"
print(device)

# Write transform for image
data_transform = transforms.Compose([
    Resize(size=(224, 224)),
    ToTensor() 
])

train_data = datasets.ImageFolder(root="/content/drive/MyDrive/電腦視覺/Dataset_OpenCvDl_Hw2_Q5/training_dataset", # target folder of images
                                  transform=data_transform, # transforms to perform on data (images)
                                  target_transform=None) # transforms to perform on labels (if necessary)

test_data = datasets.ImageFolder(root="/content/drive/MyDrive/電腦視覺/Dataset_OpenCvDl_Hw2_Q5/validation_dataset", 
                                 transform=data_transform)

train_dataloader = DataLoader(dataset=train_data, batch_size=32, shuffle=True,pin_memory=True)
test_dataloader = DataLoader(dataset=test_data, batch_size=32, shuffle=True,pin_memory=True)

print(train_data.class_to_idx)

model = resnet50(weights=None)
model.fc = nn.Linear(in_features=2048, out_features=1, bias=True)
model = model.to(device)

# hyperparameters
EPOCHS = 30
criterion = torch.nn.BCEWithLogitsLoss()
# criterion = ops.sigmoid_focal_loss
optimizer = torch.optim.Adam(model.parameters(), lr=0.0001)

for epoch in range(EPOCHS):  # loop over the dataset multiple times

    train_loss = 0.0
    test_loss = 0.0
    train_accuracy = 0.0
    test_accuracy = 0.0
    
    model.train()
    for i, data in tqdm(enumerate(train_dataloader, 0), total = len(train_dataloader),position=0, leave=True):
        # get the inputs; data is a list of [inputs, labels]
        
        inputs, labels = data
        inputs = inputs.to(device)
        labels = labels.float().to(device)
        # zero the parameter gradients
        optimizer.zero_grad()

        # forward + backward + optimize
        outputs = model(inputs).squeeze()
        loss = criterion(outputs, labels)
#         loss = ctiterion(outputs, labels , alpha = 0.4 , gamma = 1.0 , reduction='sum')
        loss.backward()
        optimizer.step()

        # print statistics
        train_loss += loss.item()
        prediction = torch.round(torch.sigmoid(outputs))
        train_accuracy += torch.eq(labels,prediction).sum().item()/len(labels)
    
    model.eval()
    with torch.inference_mode():
        for i, data in enumerate(test_dataloader, 0):
            # get the inputs; data is a list of [inputs, labels]
            inputs, labels = data
            inputs = inputs.to(device)
            labels = labels.float().to(device)

            # forward + backward + optimize
            outputs = model(inputs).squeeze()
            loss = criterion(outputs, labels)
#             loss = ctiterion(outputs, labels , alpha = 0.4 , gamma = 1.0 , reduction='mean')

            # print statistics
            test_loss += loss.item()
            prediction = torch.round(torch.sigmoid(outputs))
            test_accuracy += torch.eq(labels,prediction).sum().item()/len(labels)
    
    train_loss = train_loss/len(train_dataloader)
    train_accuracy = train_accuracy/len(train_dataloader)
    
    test_loss = test_loss/len(test_dataloader)
    test_accuracy = test_accuracy/len(test_dataloader)
    
    print(f"train loss: {train_loss} || train accuracy: {train_accuracy} || test loss: {test_loss} || test accuracy: {test_accuracy}")
        

print('Finished Training')

from pathlib import Path
